// --- lookups -------------------------------------------------------------

export const STORY_CHAPTER_COUNT = STORY_ONE.chapters.length

export const getChapter = (chapterId: string | undefined) =>
  STORY_ONE.chapters.find((c) => c.id === chapterId)

export function getStoryLevel(
  chapterId: string | undefined,
  levelId: string | undefined,
) {
  return getChapter(chapterId)?.levels.find((l) => l.id === levelId)
}
