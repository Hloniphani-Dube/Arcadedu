import type { EnemyTier } from '../lib/types'

/*
  Story Mode — a single tale, "Story I: The Long Way Round".

  A wanderer crosses twelve regions of a puzzle-world. Each region is a chapter
  with a short premise and three levels. The questions are NOT subject material —
  they're general-knowledge / lateral-thinking brain-teasers (geography, logic,
  wordplay, patterns, "how many…"), generated by the AI from the chapter theme.

  Progression: chapter N opens when N-1 is fully cleared; levels run in order
  inside a chapter. Progress persists via the shared topic_progress table with
  subject_id = STORY_ONE.id.
*/

export interface StoryLevel {
  id: string
  title: string
  tier: EnemyTier
}

export interface Chapter {
  id: string
  /** 0-based position in the tale. */
  index: number
  title: string
  premise: string
  levels: StoryLevel[]
}

export interface Story {
  id: string
  title: string
  tagline: string
  chapters: Chapter[]
}

const LEVEL_TIERS: EnemyTier[] = ['easy', 'medium', 'hard']

function chapter(
  index: number,
  title: string,
  premise: string,
  levelTitles: [string, string, string],
): Chapter {
  const id = `s1-c${index + 1}`
  return {
    id,
    index,
    title,
    premise,
    levels: levelTitles.map((t, i) => ({
      id: `${id}-${i + 1}`,
      title: t,
      tier: LEVEL_TIERS[i],
    })),
  }
}

